import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormArray, FormBuilder, FormGroup, ReactiveFormsModule, Validators } from '@angular/forms';
import { FormsModule } from '@angular/forms'; // Added FormsModule import
import { QuestionAdminService } from '../services/question-admin.service';
import { Pregunta } from '../models';
import { HttpClientModule } from '@angular/common/http';

@Component({
  selector: 'app-question-management',
  standalone: true, // Mark as standalone
  imports: [CommonModule, ReactiveFormsModule, HttpClientModule, FormsModule], // Added FormsModule
  templateUrl: './question-management.html',
  styleUrl: './question-management.scss'
})
export class QuestionManagement implements OnInit {
  questionForm: FormGroup;
  questions: Pregunta[] = [];
  editingQuestionId: string | null = null; // Changed to string for UUID
  // selectedFile: File | null = null; // Not directly used in new CRUD, might be for a separate upload feature

  constructor(private fb: FormBuilder, private questionAdminService: QuestionAdminService) { // Injected service
    this.questionForm = this.fb.group({
      idPregunta: [''], // Changed to empty string for UUID
      titulo: ['', Validators.required],
      foto: [''],
      Habilitado: [true],
      respuestas: this.fb.array([])
    });
  }

  ngOnInit() {
    this.loadQuestions();
    this.addRespuesta();
  }

  loadQuestions() {
    this.questionAdminService.getQuestionsFull().subscribe({ // Use getQuestionsFull
      next: (questions) => {
        this.questions = questions;
      },
      error: (err) => {
        console.error('Error loading questions', err);
      }
    });
  }

  get respuestas(): FormArray {
    return this.questionForm.get('respuestas') as FormArray;
  }

  newRespuesta(): FormGroup {
    return this.fb.group({
      idRespuesta: [''], // Changed to empty string for UUID
      titulo: ['', Validators.required],
      valor: [false, Validators.required], // Default to correct (false)
      foto: [''],
      seleccionada: [false]
    });
  }

  addRespuesta() {
    this.respuestas.push(this.newRespuesta());
  }

  removeRespuesta(index: number) {
    this.respuestas.removeAt(index);
  }

  onSubmit() {
    if (this.questionForm.valid) {
      const formValue = this.questionForm.value;
      const question: Pregunta = {
        idPregunta: formValue.idPregunta === '' ? '' : formValue.idPregunta, // Send empty string for new, actual UUID for update
        titulo: formValue.titulo,
        foto: formValue.foto,
        Habilitado: formValue.Habilitado,
        respuestas: formValue.respuestas.map((r: any) => ({
          idRespuesta: r.idRespuesta === '' ? '' : r.idRespuesta, // Send empty string for new, actual UUID for update
          titulo: r.titulo,
          valor: r.valor,
          foto: r.foto || 'Sin foto',
          seleccionada: false
        }))
      };

      if (this.editingQuestionId !== null && this.editingQuestionId !== '') {
        // Ensure idPregunta is set for update
        question.idPregunta = this.editingQuestionId;
        this.questionAdminService.updateQuestion(question).subscribe({
          next: () => {
            console.log('Question updated successfully');
            this.resetForm();
            this.loadQuestions();
          },
          error: (err) => {
            console.error('Error updating question', err);
          }
        });
      } else {
        // For new questions, idPregunta should be generated by the server, so send an empty string
        question.idPregunta = ''; 
        this.questionAdminService.addQuestion(question).subscribe({
          next: () => {
            console.log('Question added successfully');
            this.resetForm();
            this.loadQuestions();
          },
          error: (err) => {
            console.error('Error adding question', err);
          }
        });
      }
    }
  }

  editQuestion(question: Pregunta) {
    this.editingQuestionId = question.idPregunta; // Now a string
    this.questionForm.patchValue({
      idPregunta: question.idPregunta,
      titulo: question.titulo,
      foto: question.foto,
      Habilitado: question.Habilitado
    });
    this.respuestas.clear();
    question.respuestas.forEach(r => {
      this.respuestas.push(this.fb.group({
        idRespuesta: r.idRespuesta,
        titulo: r.titulo,
        valor: r.valor,
        foto: r.foto,
        seleccionada: r.seleccionada
      }));
    });
  }

  deleteQuestion(id: string) { // Changed to string
    if (confirm('Are you sure you want to delete this question?')) {
      this.questionAdminService.deleteQuestion(id).subscribe({
        next: () => {
          console.log('Question deleted successfully');
          this.loadQuestions();
          this.resetForm(); // Clear form after deletion
        },
        error: (err) => {
          console.error('Error deleting question', err);
        }
      });
    }
  }

  // Method to save all questions, as per original requirement
  saveAllQuestions(): void {
    if (confirm('This will overwrite all questions on the server. Are you sure?')) {
      this.questionAdminService.saveAllQuestions(this.questions).subscribe({
        next: (res) => {
          console.log('All questions saved', res);
          alert('All questions saved successfully!');
          this.loadQuestions();
        },
        error: (err) => {
          console.error('Failed to save all questions', err);
          alert('Failed to save all questions.');
        }
      });
    }
  }

  resetForm() {
    this.editingQuestionId = null; // Clear editing state
    this.questionForm.reset({ Habilitado: true, foto: '', titulo: '' }); // Reset all controls
    this.respuestas.clear();
    this.addRespuesta();
  }
}
