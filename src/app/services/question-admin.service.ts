import { Injectable } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { Observable } from 'rxjs';
import { Pregunta } from '../models'; // Assuming models.ts is in the parent directory

@Injectable({
  providedIn: 'root'
})
export class QuestionAdminService {
  private apiUrl = 'http://localhost:3000/api/questions'; // Base URL for question API

  constructor(private http: HttpClient) { }

  /**
   * Retrieves all questions with full details (including answers).
   * @returns An Observable of an array of Pregunta objects.
   */
  getQuestionsFull(): Observable<Pregunta[]> {
    return this.http.get<Pregunta[]>(`${this.apiUrl}/full`);
  }

  /**
   * Retrieves a single question by its ID.
   * @param id The UUID of the question to retrieve.
   * @returns An Observable of a Pregunta object.
   */
  getQuestionById(id: string): Observable<Pregunta> {
    return this.http.get<Pregunta>(`${this.apiUrl}/${id}`);
  }

  /**
   * Adds a new question.
   * @param question The Pregunta object to add (without idPregunta, which will be generated by the server).
   * @returns An Observable of the newly added Pregunta object.
   */
  addQuestion(question: Omit<Pregunta, 'idPregunta'>): Observable<Pregunta> {
    return this.http.post<Pregunta>(this.apiUrl, question);
  }

  /**
   * Updates an existing question.
   * @param question The Pregunta object to update (must include idPregunta).
   * @returns An Observable of the updated Pregunta object.
   */
  updateQuestion(question: Pregunta): Observable<Pregunta> {
    return this.http.put<Pregunta>(`${this.apiUrl}/${question.idPregunta}`, question);
  }

  /**
   * Deletes a question by its ID.
   * @param id The UUID of the question to delete.
   * @returns An Observable for the completion of the delete operation.
   */
  deleteQuestion(id: string): Observable<void> {
    return this.http.delete<void>(`${this.apiUrl}/${id}`);
  }

  /**
   * Saves an entire array of questions, effectively overwriting the data.js file.
   * @param questions An array of Pregunta objects to save.
   * @returns An Observable for the completion of the save operation.
   */
  saveAllQuestions(questions: Pregunta[]): Observable<{ message: string }> {
    return this.http.post<{ message: string }>(`${this.apiUrl}/save-all`, questions);
  }
}
