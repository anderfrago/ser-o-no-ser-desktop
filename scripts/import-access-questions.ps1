param(
    [string]$DatabasePath = (Join-Path $PSScriptRoot '../../seronoser.mdb')
)

$ErrorActionPreference = 'Stop'
$projectPath = Split-Path $PSScriptRoot -Parent
$database = (Resolve-Path -LiteralPath $DatabasePath).Path
$builder = [System.Data.Odbc.OdbcConnectionStringBuilder]::new()
$builder['Driver'] = 'Microsoft Access Driver (*.mdb, *.accdb)'
$builder['Dbq'] = $database
$builder['ReadOnly'] = '1'
$connection = [System.Data.Odbc.OdbcConnection]::new($builder.ConnectionString)

function Read-Table([string]$sql) {
    $command = $connection.CreateCommand()
    try {
        $command.CommandText = $sql
        $table = [System.Data.DataTable]::new()
        $table.Load($command.ExecuteReader())
        return ,$table
    } finally {
        $command.Dispose()
    }
}

function Convert-Photo($value) {
    if ($value -is [DBNull] -or [string]::IsNullOrWhiteSpace($value) -or $value -ieq 'Sin Foto') {
        return 'Sin foto'
    }
    # Relative URLs work with both the development server and Electron's file URL.
    return 'fotos/' + [Uri]::EscapeDataString([string]$value)
}

try {
    $connection.Open()
    $sourceQuestions = Read-Table 'SELECT * FROM Tpregunta ORDER BY IdPreg'
    $sourceAnswers = Read-Table 'SELECT * FROM Trespuesta ORDER BY idPreg, idResp'
    $questionIds = @{}
    $answerIds = @{}
    foreach ($row in $sourceQuestions.Rows) {
        if ($questionIds.ContainsKey([int]$row.IdPreg)) { throw "Duplicate question ID: $($row.IdPreg)" }
        $questionIds[[int]$row.IdPreg] = $true
    }
    foreach ($row in $sourceAnswers.Rows) {
        if (-not $questionIds.ContainsKey([int]$row.idPreg)) { throw "Orphan answer: $($row.idPreg)/$($row.idResp)" }
        $key = "$($row.idPreg)-$($row.idResp)"
        if ($answerIds.ContainsKey($key)) { throw "Duplicate answer ID: $key" }
        $answerIds[$key] = $true
    }
    $questions = @(
        foreach ($row in $sourceQuestions.Rows) {
            $answers = @(
                foreach ($answer in $sourceAnswers.Rows) {
                    if ($answer.idPreg -ne $row.IdPreg) { continue }
                    [ordered]@{
                        idRespuesta = "mdb-$($answer.idPreg)-$($answer.idResp)"
                        titulo = [string]$answer.TextPreg
                        valor = [bool]$answer.Respuesta
                        foto = Convert-Photo $answer.FotoResp
                        seleccionada = $false
                    }
                }
            )
            if ($answers.Count -eq 0) { throw "Question $($row.IdPreg) has no answers" }
            [ordered]@{
                idPregunta = [string]$row.IdPreg
                titulo = [string]$row.TextPreg
                Habilitado = [bool]$row.Habilitado
                foto = Convert-Photo $row.FotoPreg
                respuestas = $answers
            }
        }
    )
    if ($questions.Count -eq 0) { throw 'The database has no questions' }
    $json = ConvertTo-Json -InputObject $questions -Depth 10
    $utf8 = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText((Join-Path $projectPath 'questions.json'), $json + "`n", $utf8)
    $seed = "// Generated by scripts/import-access-questions.ps1. Do not edit manually.`nconst questions = $json;`n`nmodule.exports = { questions };`n"
    [System.IO.File]::WriteAllText((Join-Path $projectPath 'api/data.js'), $seed, $utf8)
    Write-Output "Imported $($questions.Count) questions and $($sourceAnswers.Rows.Count) answers."
} finally {
    $connection.Dispose()
}
